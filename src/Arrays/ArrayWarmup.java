package Arrays;

public class ArrayWarmup {
    public static void main(String[] args){
        int[] tempArray = new int[5];

        tempArray[0] = 45;
        tempArray[1] = 53;
        tempArray[2] = 64;
        tempArray[3] = 76;
        tempArray[4] = 89;

        for (int item: tempArray) {
            System.out.println(item);
        }


    }
}
